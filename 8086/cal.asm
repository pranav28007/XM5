ASSUME CS:CODE, DS:DATA
DATA SEGMENT
        MSG1 DB 10,13,"1.ADD 2.SUB 3.MUL 4.DIV 5.FACT 6.EXIT$"
        MSG2 DB 10,13,"ENTER CHOICE: $"
        MSG3 DB 10,13,"ENTER FIRST NUMBER: $"
        MSG4 DB 10,13,"ENTER SECOND NUMBER: $"
        MSG5 DB 10,13,"ENTER NUMBER: $"
        RESMSG DB 10,13,"RESULT: $"
 ERRMSG DB 10,13,"DIVIDE BY ZERO!$"
DATA ENDS

CODE SEGMENT
START:
    MOV AX, DATA
    MOV DS, AX

MENU:
    LEA DX, MSG1
    MOV AH, 09H
    INT 21H

    LEA DX, MSG2
    MOV AH, 09H
    INT 21H

    MOV AH, 01H
    INT 21H
    SUB AL, '0'
    MOV CH, AL

    CMP CH, 6
    JNE NEXT_EXIT
    JMP EXIT
NEXT_EXIT:

    CMP CH, 5
    JNE NEXT_FACT
    JMP FACTORIAL
NEXT_FACT:

    ; INPUT FIRST NUMBER

LEA DX, MSG3
    MOV AH, 09H
    INT 21H

    MOV AH, 01H
    INT 21H
    SUB AL, '0'
    MOV BL, AL

    ; INPUT SECOND NUMBER
    LEA DX, MSG4
    MOV AH, 09H
    INT 21H

    MOV AH, 01H
    INT 21H
    SUB AL, '0'

    CMP CH, 1
    JNE NEXT_ADD
    JMP ADDITION
NEXT_ADD:

    CMP CH, 2
    JNE NEXT_SUB
    JMP SUBTRACTION
NEXT_SUB:

    CMP CH, 3
    JNE NEXT_MUL
    JMP MULTIPLICATION

NEXT_MUL:

CMP CH, 4
    JNE MENU
    JMP DIVISION

; ADD
ADDITION:
    ADD AL, BL
    MOV AH, 0
    JMP DISPLAY

; SUB
SUBTRACTION:
    SUB BL, AL
    MOV AL, BL
    MOV AH, 0
    JMP DISPLAY

; MUL
MULTIPLICATION:
    MOV AH, 0
    MUL BL
    JMP DISPLAY

; DIV
DIVISION:
    CMP AL, 0
    JE ERROR

    MOV AH, 0
    MOV DL, AL
    MOV AL, BL
    DIV DL
    MOV AH, 0
    JMP DISPLAY

ERROR:
    LEA DX, ERRMSG
    MOV AH, 09H
    INT 21H
    JMP MENU

; FACTORIAL
FACTORIAL:
    LEA DX, MSG5
    MOV AH, 09H
    INT 21H

    MOV AH, 01H
    INT 21H
    SUB AL, '0'

    MOV CL, AL
    MOV AX, 1

    CMP CL, 0
    JE FACT_END

FACT_LOOP:
    MUL CL
    DEC CL
    CMP CL, 1
    JNE FACT_LOOP

FACT_END:
    JMP DISPLAY

; DISPLAY
DISPLAY:
    LEA DX, RESMSG
    MOV AH, 09H
    INT 21H

    MOV BX, 10
    MOV CX, 0

CONVERT:
    MOV DX, 0
    DIV BX
    PUSH DX
    INC CX
    CMP AX, 0
    JNE CONVERT
PRINT:
    POP DX
    ADD DL, '0'
    MOV AH, 02H
    INT 21H
    LOOP PRINT

    JMP MENU

EXIT:
    MOV AH, 4CH
    INT 21H

CODE ENDS
END START
